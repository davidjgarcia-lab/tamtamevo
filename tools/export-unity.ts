// Exports the creature system (families, part library, skeleton, baked evolved forms) to the Unity project
// as JSON, so Unity always shows the same Tamtams as the web/app prototype (single source of truth: packages/core + packages/art).
// Usage: node --no-warnings --experimental-transform-types --import ./tools/ts/register.mjs tools/export-unity.ts [forms=80]
import { mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import {
  AFFINITY_WEIGHTS, CHISPIN_GENOME, EYE_STYLES, FAMILIES, FAMILY_IDS, formName, genomeSpace, genomeStats, MUTATIONS, PATTERNS, rollEvolution,
  GAITS, motionFor, STARTERS, starterGenome, type CareProfile, type Genome,
} from "../packages/core/src/index.ts";
import {
  backParts, bodyParts, chispinRig, eyeParts, FAMILY_COLORS, genomePalette, genomeRig, headParts, legParts, patternParts, SHARED_PART_IDS, STARTER_EYES, tailParts,
} from "../packages/art/src/index.ts";

type AnyPart = { id?: string; bone: string; d: string; z: number; fill?: Paint; stroke?: Paint; strokeWidth?: number; blur?: number; emissive?: boolean; sheen?: boolean; face?: { slot: string; states: string[] }; tiers?: [number, number] };
type Paint = { tint?: string; color?: string; alpha?: number; gradient?: string[]; from?: [number, number]; to?: [number, number] };

const OUT = resolve(import.meta.dirname, "../unity/TamTamEVO/Assets/TamTam/Data/Evolution");
const nForms = Number(process.argv[2] ?? 80);

/** Flat, JsonUtility-friendly paint. kind: "" (none) | tint | color | gradient. */
const paint = (p?: Paint) =>
  !p ? { kind: "", token: "", hex: "", alpha: 1, stops: [], fx: 0, fy: 0, tx: 0, ty: 0 }
    : p.gradient ? { kind: "gradient", token: "", hex: "", alpha: p.alpha ?? 1, stops: p.gradient, fx: p.from![0], fy: p.from![1], tx: p.to![0], ty: p.to![1] }
    : p.tint ? { kind: "tint", token: p.tint, hex: "", alpha: p.alpha ?? 1, stops: [], fx: 0, fy: 0, tx: 0, ty: 0 }
    : { kind: "color", token: "", hex: p.color!, alpha: p.alpha ?? 1, stops: [], fx: 0, fy: 0, tx: 0, ty: 0 };
const part = (p: AnyPart, i: number) => ({
  id: p.id ?? `p${i}`, bone: p.bone, d: p.d, z: p.z, fill: paint(p.fill), stroke: paint(p.stroke), strokeWidth: p.strokeWidth ?? 0,
  blur: p.blur ?? 0, emissive: !!p.emissive, sheen: !!p.sheen, faceSlot: p.face?.slot ?? "", faceStates: p.face?.states ?? [], tiers: p.tiers ?? [],
});
const parts = (ps: AnyPart[]) => ps.map(part);

const skeleton = {
  id: chispinRig.id,
  bones: chispinRig.bones.map((b) => ({ id: b.id, parent: b.parent ?? "", x: b.x, y: b.y, rot: b.rot ?? 0 })),
  secondary: (chispinRig.secondary ?? []).map((s) => ({ ...s })),
  breathBone: chispinRig.breathBone ?? "", eyeBones: chispinRig.eyeBones ?? [],
};

// ── Part library: every family × slot × variant (2 variants) + eyes + patterns ──────────
const slots = { body: bodyParts, head: headParts, tail: tailParts, back: backParts, legs: (f: never, v: number) => legParts(f, v).parts } as const;
const library: { slot: string; label: string; family: string; variant: number; float: boolean; parts: ReturnType<typeof parts> }[] = [];
for (const [slot, fn] of Object.entries(slots))
  for (const f of FAMILY_IDS) for (const v of [0, 1])
    library.push({ slot, label: `${f}_${v}`, family: f, variant: v, float: slot === "legs" ? legParts(f as never, v).float : false, parts: parts((fn as (f: string, v: number) => AnyPart[])(f, v)) });
library.push({ slot: "shared", label: "chispin", family: "", variant: 0, float: false, parts: parts(chispinRig.parts.filter((p) => SHARED_PART_IDS.has(p.id)) as AnyPart[]) });
for (const e of EYE_STYLES) library.push({ slot: "eyes", label: e, family: "", variant: 0, float: false, parts: parts(eyeParts(e) as AnyPart[]) });
for (const p of PATTERNS) library.push({ slot: "pattern", label: p, family: "", variant: 0, float: false, parts: parts(patternParts(p) as AnyPart[]) });

const catalog = {
  version: 1,
  note: "GENERATED by tools/export-unity.ts — do not edit by hand. Source of truth: packages/core (genetics) + packages/art (modular parts).",
  combinations: genomeSpace(),
  families: FAMILY_IDS.map((id) => {
    const f = FAMILIES[id];
    const c = FAMILY_COLORS[id];
    return { id, name: f.name, element: f.element, bases: c.bases, accent: c.accent, eye: c.eye, glow: c.glow, particleShape: c.particle.shape, particleColor: c.particle.color, prefixes: f.prefixes, suffix: f.suffix, skill: f.skill, locomotion: f.locomotion, stats: f.stats, affinity: AFFINITY_WEIGHTS[id] };
  }),
  eyeStyles: [...EYE_STYLES], patterns: [...PATTERNS], mutations: [...MUTATIONS],
  skeleton, library,
  /** Starters (egg hatches one at random), with their personality and baby motion; gaits per family/stage. */
  starters: STARTERS.map((st) => {
    const art = st.family === "plasma" && st.variant === 1 ? "plasma_baby2" : `${st.family}_baby`;
    const eye = STARTER_EYES[art];
    return { id: st.id, family: st.family, variant: st.variant, species: st.species, title: st.title, traits: st.traitLabels, favoriteFood: st.favoriteFood,
      art, eye: eye ?? null, motion: motionFor(st.family, "baby", st.motion), genome: starterGenome(st),
      lines: [...st.lines.happy, ...st.lines.bored, ...st.lines.hungry, ...st.lines.lonely] };
  }),
  motions: FAMILY_IDS.flatMap((f) => (["initial", "intermediate", "final"] as const).map((stage) => ({ family: f, stage, gait: GAITS[f][stage], motion: motionFor(f, stage) }))),
  /** Assembly rules (mirror of genomeRig in packages/art/src/modular/build.ts). */
  assembly: { order: ["shared", "body", "head", "eyes", "legs", "tail", "back", "pattern"], floatBodyLift: 14, floatBone: "body" },
};

// ── Baked forms: pure families (both variants) + care-driven random evolutions ─────────
const pure = (f: (typeof FAMILY_IDS)[number], v: number): Genome => ({
  parts: { body: f, head: f, legs: f, tail: f, back: f }, variant: { body: v, head: v, legs: v, tail: v, back: v },
  eyes: CHISPIN_GENOME.eyes, pattern: CHISPIN_GENOME.pattern, palette: { base: f, shade: v, accent: f }, mutation: "none",
} as Genome);
const styles: CareProfile[] = [];
for (let i = 0; i < 12; i++) {
  const r = (k: number) => (Math.sin(i * 12.9898 + k * 78.233) * 43758.5453) % 1;
  const a = (k: number) => Math.abs(r(k));
  styles.push({ care: a(1), affection: a(2), hygiene: a(3), training: a(4), fighting: a(5), study: a(6), play: a(7), neglect: 1 - a(1) } as CareProfile);
}
const key = (g: Genome) => `${g.parts.body}${g.variant.body}-${g.parts.head}${g.variant.head}-${g.parts.legs}${g.variant.legs}-${g.parts.tail}${g.variant.tail}-${g.parts.back}${g.variant.back}-${g.eyes}-${g.pattern}-${g.palette.base}${g.palette.shade}${g.palette.accent}-${g.mutation}`;
const forms = new Map<string, Genome>();
for (const f of FAMILY_IDS) for (const v of [0, 1]) forms.set(key(pure(f, v)), pure(f, v));
for (let seed = 1; forms.size < nForms && seed < 10_000; seed++) {
  const g = rollEvolution(CHISPIN_GENOME, styles[seed % styles.length]!, seed * 7919).genome;
  forms.set(key(g), g);
}

rmSync(join(OUT, "Forms"), { recursive: true, force: true });
mkdirSync(join(OUT, "Forms"), { recursive: true });
writeFileSync(join(OUT, "catalog.json"), JSON.stringify(catalog));
const index: { key: string; name: string; file: string }[] = [];
for (const [k, g] of forms) {
  const { rig, float } = genomeRig(g as never);
  const name = formName(g, 1);
  const file = `${k}.json`;
  writeFileSync(join(OUT, "Forms", file), JSON.stringify({
    key: k, name, genome: g, float, palette: genomePalette(g as never), stats: genomeStats(g),
    rig: { id: rig.id, bones: rig.bones.map((b) => ({ id: b.id, parent: b.parent ?? "", x: b.x, y: b.y, rot: b.rot ?? 0 })), parts: parts(rig.parts as AnyPart[]), secondary: skeleton.secondary, breathBone: skeleton.breathBone, eyeBones: skeleton.eyeBones },
  }));
  index.push({ key: k, name, file });
}
writeFileSync(join(OUT, "forms_index.json"), JSON.stringify({ forms: index }, null, 1));
console.log(`catalog: ${catalog.families.length} families, ${library.length} library entries, ${catalog.combinations.toLocaleString("es-ES")} combinations`);
console.log(`forms: ${index.length} baked → ${OUT}`);
console.log(readdirSync(join(OUT, "Forms")).length, "form files");
