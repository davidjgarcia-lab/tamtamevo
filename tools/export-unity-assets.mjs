// Renders the nest-house environment assets with the web prototype's own drawing code and saves them in Unity:
// unity/TamTamEVO/Assets/TamTam/Art/Environments/NestHouse/{Walls,Floors,Landscapes,Rooms,Furniture,Paintings}/*.png + assets.json
// Usage: (cd apps/mobile && EXPO_OFFLINE=1 pnpm web:build) && node tools/export-unity-assets.mjs
import { createServer } from "node:http";
import { mkdirSync, writeFileSync } from "node:fs";
import { readFile } from "node:fs/promises";
import { dirname, extname, join, resolve } from "node:path";
import { createRequire } from "node:module";
import { execSync } from "node:child_process";

const require = createRequire(import.meta.url);
let playwright;
try { playwright = require("playwright"); } catch { playwright = require(join(execSync("npm root -g").toString().trim(), "playwright")); }
const root = resolve(process.env.DIST ?? resolve(import.meta.dirname, "../apps/mobile/dist"));
const OUT = resolve(import.meta.dirname, "../unity/TamTamEVO/Assets/TamTam/Art/Environments/NestHouse");
const types = { ".html": "text/html", ".js": "text/javascript", ".wasm": "application/wasm", ".ttf": "font/ttf", ".png": "image/png", ".webp": "image/webp" };
const server = createServer(async (req, res) => {
  const url = decodeURIComponent((req.url ?? "/").split("?")[0]);
  const file = join(root, url === "/" ? "index.html" : url);
  try { const b = await readFile(file); res.writeHead(200, { "content-type": types[extname(file)] ?? "application/octet-stream" }); res.end(b); }
  catch { res.writeHead(404).end(); }
}).listen(0);
const browser = await playwright.chromium.launch();
const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
try {
  await page.goto(`http://localhost:${server.address().port}/`);
  await page.getByTestId("stage").waitFor({ timeout: 30000 });
  await page.getByTestId("dev").click();
  await page.getByTestId("debug-enter").click();
  await page.waitForTimeout(1200);
  await page.getByTestId("dbg-export-assets").click();
  await page.waitForFunction(() => Array.isArray(globalThis.__tamtamUnityExport), null, { timeout: 30000 });
  const list = await page.evaluate(() => globalThis.__tamtamUnityExport);
  const meta = [];
  for (const a of list) {
    const p = join(OUT, a.path);
    mkdirSync(dirname(p), { recursive: true });
    if (a.png) writeFileSync(p, Buffer.from(a.png, "base64"));
    else writeFileSync(p, JSON.stringify(a.meta, null, 1));
    if (a.meta && a.png) meta.push({ path: a.path, ...a.meta });
  }
  writeFileSync(join(OUT, "assets.json"), JSON.stringify({ note: "GENERATED by tools/export-unity-assets.mjs from apps/mobile/src/home/roomArt.ts", assets: meta }, null, 1));
  console.log(`${list.length} assets → ${OUT}`);
} finally {
  await browser.close();
  server.close();
}
